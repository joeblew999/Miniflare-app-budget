// Generates src/themes.css: one block of official shadcn CSS variables per accent theme.
// For each theme it encodes a preset (same as the project's, with theme + chartColor swapped),
// runs `shadcn init --preset` in a scratch copy, and extracts the :root and .dark blocks.
// Usage: npm run theme:gen            (all themes, ~20s each)
//        npm run theme:gen -- --json   (only rebuild src/themes.json from the existing themes.css)
import { execSync } from "node:child_process"
import { cpSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"

const root = process.cwd()
const { decodePreset, encodePreset, PRESET_THEMES, PRESET_BASE_COLORS } = await import(
  path.join(root, "node_modules/shadcn/dist/preset/index.js")
)

const primaryOf = (blockText) => blockText.match(/--primary:\s*([^;]+);/)[1].trim()
const writeJson = (css, def) => {
  const themes = [...css.matchAll(/\/\* (\S+) — preset (\S+) \*\/\n:root\[data-accent="[^"]+"\] \{([^}]*)\}/g)]
    .map(([, name, preset, body]) => ({ name, preset, primary: primaryOf(body) }))
  writeFileSync(path.join(root, "src/themes.json"), JSON.stringify({ default: def, themes }, null, 2) + "\n")
  console.log(`wrote src/themes.json (${themes.length} themes)`)
}

if (process.argv.includes("--json")) {
  const css = readFileSync(path.join(root, "src/themes.css"), "utf8")
  writeJson(css, decodePreset(execSync("npx shadcn preset resolve", { cwd: root, encoding: "utf8" }).match(/code\s+(\S+)/)[1]).theme)
  process.exit(0)
}

const current = execSync("npx shadcn preset resolve", { cwd: root, encoding: "utf8" })
const code = current.match(/code\s+(\S+)/)[1]
const base = decodePreset(code)
// Accent themes = everything that isn't a base colour, plus the base colour itself (plain look)
const themes = [base.baseColor, ...PRESET_THEMES.filter((t) => !PRESET_BASE_COLORS.includes(t))]

const block = (css, sel) => {
  const i = css.indexOf(sel + " {")
  return css.slice(css.indexOf("{", i) + 1, css.indexOf("}", i)).trim()
}

let out = `/* Generated by scripts/gen-themes.mjs from shadcn presets — do not edit by hand.
   Base preset: ${code} (baseColor ${base.baseColor}). Switch at runtime with <html data-accent="…">. */\n`
for (const theme of themes) {
  const preset = encodePreset({ ...base, theme, chartColor: theme })
  const dir = mkdtempSync(path.join(tmpdir(), "theme-"))
  for (const f of ["package.json", "components.json", "tsconfig.json", "tsconfig.app.json", "vite.config.ts", "src"])
    cpSync(path.join(root, f), path.join(dir, f), { recursive: true })
  symlinkSync(path.join(root, "node_modules"), path.join(dir, "node_modules"))
  execSync(`npx shadcn init --preset ${preset} --force --no-reinstall --yes`, { cwd: dir, stdio: "ignore" })
  const css = readFileSync(path.join(dir, "src/index.css"), "utf8")
  out += `\n/* ${theme} — preset ${preset} */\n:root[data-accent="${theme}"] {\n  ${block(css, ":root")}\n}\n`
  out += `:root.dark[data-accent="${theme}"] {\n  ${block(css, ".dark")}\n}\n`
  rmSync(dir, { recursive: true, force: true })
  console.log(`${theme.padEnd(8)} ${preset}`)
}
writeFileSync(path.join(root, "src/themes.css"), out)
writeJson(out, base.theme)
console.log(`wrote src/themes.css (${themes.length} themes)`)
